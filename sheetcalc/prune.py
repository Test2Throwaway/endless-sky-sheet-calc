"""MVP pruner: strict dominance; per solar case the power and cooling plant search, the engine pass and
the regeneration pass; the weapon
lenses.

Usage: python -m sheetcalc.prune [--jobs N] [--solar normal,dark]

Writes reports/pruned.json (for the optimizer) and reports/pruned.md (for reading). For a request in solar case
S, drop every outfit under "strict" plus every outfit under "power"/S, "engines"/S and "regeneration"/S; for a general-purpose combat request, also
the outfits under "weapons"/"damage" and "weapons"/"anti-missile". See docs/pruner-design.md for what comes
after the MVP.
"""

import argparse
import json
import os
import time
from collections import Counter
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

from .availability import DEFAULT_IN_PLAY, load_in_play
from .engines import engine_dominance, rate_box
from .regen import regen_dominance
from .gamedata import DEFAULT_DATA_DIR, load_outfits
from .ladders import generators, passive_coolers
from .obsolescence import analyse_items
from .power import active_coolers
from .settings import OBSOLESCENCE_ENERGY, OBSOLESCENCE_HEAT, REFERENCE_LOADS, SOLAR_SCENARIOS
from .strict import strict_dominance
from .weapons import LENSES, lens_dominance

_DATA = {}


def _init_worker(outfits, availability):
    _DATA["outfits"], _DATA["availability"] = outfits, availability


def power_pass(solar, energies=OBSOLESCENCE_ENERGY, heats=OBSOLESCENCE_HEAT):
    """Generators and coolers the best power plant never needs in this solar case.

    Outfits with stats beyond steady power and cooling (storage, resistances, multipliers...) are kept: the
    optimizer may want them for those."""
    outfits, availability = _DATA["outfits"], _DATA["availability"]
    scenario = SOLAR_SCENARIOS[solar]
    verdicts, plant = analyse_items(passive_coolers(outfits, availability), generators(outfits, availability, scenario)[0],
                                active_coolers(outfits, availability), availability, energies, heats, outfits,
                                heat_fraction=scenario.heat_fraction)
    dropped, kept_for_other_stats = {}, {}
    for v in sorted(verdicts.values(), key=lambda v: v.name):
        if v.status == "kept" or " + " in v.name:
            continue
        if v.extras:
            kept_for_other_stats[v.name] = v.extras
        else:
            dropped[v.name] = {"family": v.family, "why": v.status + (f": {v.reason}" if v.reason else "")}
    prices = {ship: dict(zip(("energy", "heat"), plant.prices(*load))) for ship, load in REFERENCE_LOADS.items()}
    return solar, dropped, kept_for_other_stats, prices


def report(result, outfits):
    considered = result["pool"]["considered"]
    strict = result["strict"]
    lines = ["# Pruned outfits", "",
             "Generated by `python -m sheetcalc.prune`. For a request in solar case S, the optimizer can skip every",
             "outfit under *Strict* plus every outfit under *Power*, *Engines* and *Regeneration* for S.", "",
             "## Summary", "",
             f"In play: {result['pool']['in play']}; considered (designable categories): {considered}.", "",
             "| Solar case | Strict | Power | Engines | Regeneration | Total dropped | Share of considered |",
             "|---|---|---|---|---|---|---|"]
    for solar, p in result["power"].items():
        engines = len(result["engines"][solar]["dropped"])
        regen = len(result["regeneration"][solar]["dropped"])
        total = len(strict) + len(p["dropped"]) + engines + regen
        lines.append(f"| {solar} | {len(strict)} | {len(p['dropped'])} | {engines} | {regen} | {total} "
                     f"| {total / considered:.0%} |")
    lines += ["", "Weapon lenses (general-purpose combat requests only), on what strict dominance keeps:", "",
              "| Lens | Weapons in lens | Dropped | Share |", "|---|---|---|---|"]
    for lens, w in result["weapons"].items():
        n = w["in lens"]
        lines.append(f"| {lens} | {n} | {len(w['dropped'])} | {len(w['dropped']) / n:.0%} |" if n else f"| {lens} | 0 | 0 | – |")
    by_cat = Counter(outfits[n].get("category") for n in strict)
    lines += ["", "## Strict dominance", "",
              "Dropped because another outfit (or whole copies of it) is at least as good in every way. Valid for",
              "every request.", "",
              "By category: " + ", ".join(f"{c} {n}" for c, n in by_cat.most_common()) + ".", "",
              "| Outfit | Beaten by (copies needed) |", "|---|---|"]
    for name, beaters in strict.items():
        lines.append(f"| {name} | " + ", ".join(f"{b}" + (f" ×{k}" if k > 1 else "") for b, k in beaters.items()) + " |")
    for solar, p in result["power"].items():
        lines += ["", f"## Power and cooling: {solar}", "",
                  "| Outfit | Family | Why |", "|---|---|---|"]
        lines += [f"| {n} | {d['family']} | {d['why']} |" for n, d in p["dropped"].items()]
        if p["kept for other stats"]:
            lines += ["", "Not needed for power here, but kept for other stats: "
                      + ", ".join(sorted(p["kept for other stats"])) + "."]
    for solar, e in result["engines"].items():
        prices = result["power"][solar]["prices"]
        lines += ["", f"## Engines: {solar}", "",
                  "Dropped because another engine (or whole copies of it) is at least as good on every stat once",
                  "thrusting and turning energy and heat are priced in outfit space at this case's power plant rates",
                  "(thrust and turn duty each at 0% and 100%), at every corner of the rate box. Rates in space per energy/s and per heat/s:",
                  ", ".join(f"{ship} {p['energy']:.4f} / {p['heat']:.5f}" for ship, p in prices.items()) + ".", "",
                  f"{len(e['dropped'])} of {e['considered']} engines kept by strict dominance.", "",
                  "| Engine | Beaten by (copies needed) |", "|---|---|"]
        lines += [f"| {n} | " + ", ".join(b + (f" ×{k}" if k > 1 else "") for b, k in beaters.items()) + " |"
                  for n, beaters in e["dropped"].items()]
    for solar, e in result["regeneration"].items():
        lines += ["", f"## Regeneration: {solar}", "",
                  "Dropped because another outfit (or whole copies of it) is at least as good on regeneration and every",
                  "other stat, once space, steady power and regeneration energy and heat are priced at this case's rates,",
                  "at 0% and 100% regeneration duty.", "",
                  f"{len(e['dropped'])} of {e['considered']} regeneration outfits kept by strict dominance.", "",
                  "| Outfit | Beaten by (copies needed) |", "|---|---|"]
        lines += [f"| {n} | " + ", ".join(b + (f" ×{k}" if k > 1 else "") for b, k in beaters.items()) + " |"
                  for n, beaters in e["dropped"].items()]
    for lens, w in result["weapons"].items():
        lines += ["", f"## Weapon lens: {lens}", "",
                  "Dropped for general-purpose combat requests only: another weapon in the same category is at least",
                  "as good on every stat this lens compares (docs/tier-table.md, section 2a).", ""]
        if w["dropped"]:
            lines += ["| Weapon | Beaten by |", "|---|---|"]
            lines += [f"| {n} | {', '.join(b)} |" for n, b in w["dropped"].items()]
        else:
            lines.append("Nothing: every weapon in this lens trades one compared stat against another.")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--data", default=DEFAULT_DATA_DIR, type=Path)
    parser.add_argument("--in-play", default=DEFAULT_IN_PLAY, type=Path)
    parser.add_argument("--out", default=Path(__file__).resolve().parents[1] / "reports", type=Path)
    parser.add_argument("--jobs", type=int, default=os.cpu_count())
    parser.add_argument("--solar", default=",".join(SOLAR_SCENARIOS), help="comma-separated solar cases")
    args = parser.parse_args()
    solars = args.solar.split(",")
    for s in solars:
        if s not in SOLAR_SCENARIOS:
            parser.error(f"unknown solar case {s!r}; choose from {', '.join(SOLAR_SCENARIOS)}")

    start = time.time()
    outfits, availability = load_outfits(args.data), load_in_play(args.in_play)
    considered, strict = strict_dominance(outfits, availability)
    survivors = {n: a for n, a in availability.items() if n not in strict}
    with ProcessPoolExecutor(max_workers=args.jobs, initializer=_init_worker,
                             initargs=(outfits, survivors)) as executor:
        results = list(executor.map(power_pass, solars))
    engines, regen = {}, {}
    for s, _, _, prices in results:
        considered_engines, dropped = engine_dominance(outfits, survivors, rate_box(prices))
        engines[s] = {"considered": len(considered_engines), "dropped": dropped}
        considered_regen, dropped = regen_dominance(outfits, survivors, prices)
        regen[s] = {"considered": len(considered_regen), "dropped": dropped}
    weapons = {}
    for lens in LENSES:
        in_lens, dropped = lens_dominance(outfits, survivors, lens)
        weapons[lens] = {"in lens": len(in_lens), "dropped": dict(sorted(dropped.items()))}
    result = {
        "pool": {"in play": len(availability), "considered": len(considered)},
        "strict": strict,
        "power": {s: {"dropped": d, "kept for other stats": k, "prices": p} for s, d, k, p in results},
        "engines": engines,
        "regeneration": regen,
        "weapons": weapons,
    }
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "pruned.json").write_text(json.dumps(result, indent=1) + "\n", encoding="utf-8")
    (args.out / "pruned.md").write_text(report(result, outfits), encoding="utf-8")
    for s, d, _, _ in results:
        total = len(strict) + len(d) + len(engines[s]["dropped"]) + len(regen[s]["dropped"])
        print(f"{s}: {total} of {len(considered)} dropped ({total / len(considered):.0%})")
    for lens, w in weapons.items():
        print(f"weapon lens {lens}: {len(w['dropped'])} of {w['in lens']} dropped")
    print(f"{time.time() - start:.0f}s; wrote pruned.json and pruned.md to {args.out}")


if __name__ == "__main__":
    main()
