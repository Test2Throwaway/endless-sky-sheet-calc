"""Run obsolescence passes: one per combination of design options, in parallel.

A pass prunes one family of outfits for one set of design options (for power: how much
sunlight the design can count on, and which availability tier it's allowed). The optimizer
picks the pass that matches what it's designing for. See docs/passes.md for the catalogue
and why families can be run independently.

Usage: python -m sheetcalc.passes [--jobs N] [--solar none,median] [--availability sold,all]
"""

import argparse
import json
import os
import time
from concurrent.futures import ProcessPoolExecutor, as_completed
from pathlib import Path

from .availability import DEFAULT_IN_PLAY, load_in_play
from .gamedata import DEFAULT_DATA_DIR, load_outfits
from .ladders import generators, passive_coolers
from .obsolescence import analyse_items
from .power import active_coolers
from .settings import OBSOLESCENCE_ENERGY, OBSOLESCENCE_HEAT, REFERENCE_LOADS, SOLAR_SCENARIOS

# Availability tiers, from easiest to hardest to get. A tier's pool includes every easier tier.
TIERS = {
    "sold": "bought in an outfitter (licences permitting)",
    "taken": "also taken from ships: plunder, capture, flotsam",
    "all": "also mission and event outfits",
}
FAMILIES = ["passive cooler", "active cooler", "generator"]


def tier_of(availability):
    if availability.source == "sold":
        return "sold"
    if availability.source.startswith("taken from ships"):
        return "taken"
    return "all"


def pool(availability, tier):
    """The outfits a design limited to `tier` may use."""
    allowed = list(TIERS)[:list(TIERS).index(tier) + 1]
    return {name: a for name, a in availability.items() if tier_of(a) in allowed}


def pass_id(solar, tier):
    return f"power/solar={solar}/availability={tier}"


# Worker processes get the game data once, through the pool initializer.
_DATA = {}


def _init_worker(outfits, availability):
    _DATA["outfits"], _DATA["availability"] = outfits, availability


def run_power_pass(solar, tier, energies=OBSOLESCENCE_ENERGY, heats=OBSOLESCENCE_HEAT):
    """One power-and-cooling pass. Returns (pass id, result dict, seconds)."""
    start = time.time()
    outfits, availability = _DATA["outfits"], pool(_DATA["availability"], tier)
    scenario = SOLAR_SCENARIOS[solar]
    verdicts, plant = analyse_items(passive_coolers(outfits, availability), generators(outfits, availability, scenario)[0],
                                active_coolers(outfits, availability), availability, energies, heats, outfits,
                                heat_fraction=scenario.heat_fraction)
    singles = [v for v in verdicts.values() if " + " not in v.name or v.status == "kept"]
    result = {
        "options": {"solar": solar, "availability": tier},
        "kept": {f: sorted(v.name for v in singles if v.family == f and v.status == "kept") for f in FAMILIES},
        "dropped": {v.name: {"family": v.family, "status": v.status, "reason": v.reason, "other stats": v.extras}
                    for v in sorted(singles, key=lambda v: v.name) if v.status != "kept"},
        "if banned": {v.name: v.penalty for v in singles if v.status == "kept" and v.penalty},
        # Space per energy/s and per heat/s at each reference load, for pricing other families.
        "prices": {ship: dict(zip(("energy", "heat"), plant.prices(*load))) for ship, load in REFERENCE_LOADS.items()},
    }
    return pass_id(solar, tier), result, time.time() - start


def robust_kept(passes, availability, solar):
    """Per family, the outfits kept for `solar` by the pass of their own availability tier.

    An outfit is only dropped here if outfits no harder to get always replace it, so the
    list stays valid for a player who can't get every plundered outfit."""
    kept = {f: set() for f in FAMILIES}
    for tier in TIERS:
        result = passes.get(pass_id(solar, tier))
        if result is None:
            continue
        for family, names in result["kept"].items():
            kept[family].update(n for n in names if tier_of(availability[n.split(" + ")[0]]) == tier)
    return {f: sorted(names) for f, names in kept.items()}


def price_envelope(passes):
    """Lowest and highest energy and heat prices over every pass and reference load: the
    range other families' true costs are judged over."""
    prices = [p for r in passes.values() for p in r["prices"].values()]
    return {k: [min(p[k] for p in prices), max(p[k] for p in prices)] for k in ("energy", "heat")}


def report(passes, robust, availability, solars, tiers, timings):
    lines = ["# Obsolescence passes: power and cooling", "",
             "One pass per design option combination. Pick the pass that matches what is being designed for;",
             "*robust* lists keep an outfit unless outfits that are no harder to get always replace it.",
             "Generated by `python -m sheetcalc.passes`; see docs/passes.md.", "",
             "## Options", "", "| Solar | Energy multiplier | Heat multiplier |", "|---|---|---|"]
    for s in solars:
        sc = SOLAR_SCENARIOS[s]
        lines.append(f"| {s} | ×{sc.solar_energy:.3f} | ×{sc.solar_heat:.3f} |")
    lines += ["", "| Availability | Pool |", "|---|---|"] + [f"| {t} | {TIERS[t]} |" for t in tiers]
    columns = [(s, t) for s in solars for t in tiers + ["robust"]]
    family_of = {n: f for r in list(passes.values()) for f, fam in r["kept"].items() for n in fam}
    family_of.update({n: f for r in robust.values() for f, fam in r.items() for n in fam})

    def kept(n, s, t):
        if t == "robust":
            return n in robust[f"power/solar={s}"][family_of[n]]
        r = passes.get(pass_id(s, t))
        return r is not None and n in r["kept"][family_of[n]]

    lines += ["", "## Kept outfits by pass", "",
              "| Outfit | Family | Availability | " + " | ".join(f"{s}/{t}" for s, t in columns) + " |",
              "|---" * (len(columns) + 3) + "|"]
    for n in sorted(family_of, key=lambda n: (FAMILIES.index(family_of[n]), n)):
        lines.append(f"| {n} | {family_of[n]} | {tier_of(availability[n.split(' + ')[0]])} | "
                     + " | ".join("✓" if kept(n, s, t) else "" for s, t in columns) + " |")
    env = price_envelope(passes)
    lines += ["", "## Prices", "",
              "Space per energy/s and per heat/s at the reference loads (`REFERENCE_LOADS`), per pass. Other",
              "families judge true cost over the whole range (the envelope).", "",
              "| Pass | " + " | ".join(f"{ship} energy | {ship} heat" for ship in REFERENCE_LOADS) + " |",
              "|---" * (2 * len(REFERENCE_LOADS) + 1) + "|"]
    for s, t in [(s, t) for s in solars for t in tiers]:
        r = passes.get(pass_id(s, t))
        if r:
            lines.append(f"| {s}/{t} | " + " | ".join(f"{r['prices'][ship]['energy']:.4f} | {r['prices'][ship]['heat']:.5f}"
                                                   for ship in REFERENCE_LOADS) + " |")
    lines += ["", f"Envelope: energy {env['energy'][0]:.4f}–{env['energy'][1]:.4f}, "
              f"heat {env['heat'][0]:.5f}–{env['heat'][1]:.5f} space per unit/s."]
    lines += ["", "## Counts", "", "| Pass | " + " | ".join(FAMILIES) + " | seconds |", "|---" * (len(FAMILIES) + 2) + "|"]
    for s, t in columns:
        r = passes.get(pass_id(s, t))
        if r:
            lines.append(f"| {s}/{t} | " + " | ".join(str(len(r["kept"][f])) for f in FAMILIES)
                         + f" | {timings[pass_id(s, t)]:.0f} |")
    for s in solars:
        lines.append(f"| {s}/robust | " + " | ".join(str(len(robust[f'power/solar={s}'][f])) for f in FAMILIES) + " | |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--data", default=DEFAULT_DATA_DIR, type=Path)
    parser.add_argument("--in-play", default=DEFAULT_IN_PLAY, type=Path)
    parser.add_argument("--out", default=Path(__file__).resolve().parents[1] / "reports", type=Path)
    parser.add_argument("--jobs", type=int, default=os.cpu_count(), help="worker processes (default: all cores)")
    parser.add_argument("--solar", default=",".join(SOLAR_SCENARIOS), help="comma-separated solar cases")
    parser.add_argument("--availability", default=",".join(TIERS), help="comma-separated availability tiers")
    args = parser.parse_args()
    solars, tiers = args.solar.split(","), args.availability.split(",")
    for s in solars:
        if s not in SOLAR_SCENARIOS:
            parser.error(f"unknown solar case {s!r}; choose from {', '.join(SOLAR_SCENARIOS)}")
    for t in tiers:
        if t not in TIERS:
            parser.error(f"unknown availability tier {t!r}; choose from {', '.join(TIERS)}")

    outfits, availability = load_outfits(args.data), load_in_play(args.in_play)
    passes, timings = {}, {}
    start = time.time()
    # Slowest first (biggest pools), so the pool of workers drains evenly.
    jobs = sorted(((s, t) for s in solars for t in tiers), key=lambda st: -list(TIERS).index(st[1]))
    with ProcessPoolExecutor(max_workers=args.jobs, initializer=_init_worker,
                             initargs=(outfits, availability)) as executor:
        futures = [executor.submit(run_power_pass, s, t) for s, t in jobs]
        for future in as_completed(futures):
            pid, result, seconds = future.result()
            passes[pid], timings[pid] = result, seconds
            print(f"{pid}: {seconds:.0f}s", flush=True)
    robust = {f"power/solar={s}": robust_kept(passes, availability, s) for s in solars}

    args.out.mkdir(parents=True, exist_ok=True)
    output = {
        "settings": {"loads": {"energy": OBSOLESCENCE_ENERGY, "heat": OBSOLESCENCE_HEAT},
                     "solar": {s: vars(SOLAR_SCENARIOS[s]) for s in solars}, "availability": {t: TIERS[t] for t in tiers}},
        "passes": dict(sorted(passes.items())),
        "robust": robust,
        "price envelope": price_envelope(passes),
    }
    (args.out / "passes.json").write_text(json.dumps(output, indent=1) + "\n", encoding="utf-8")
    (args.out / "passes.md").write_text(report(passes, robust, availability, solars, tiers, timings), encoding="utf-8")
    print(f"{len(passes)} passes in {time.time() - start:.0f}s; wrote passes.json and passes.md to {args.out}")


if __name__ == "__main__":
    main()
