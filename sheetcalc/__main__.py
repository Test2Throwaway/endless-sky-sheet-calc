"""Build the cooling and energy ladders and write them to reports/.

Usage: python -m sheetcalc [--data DIR] [--in-play FILE] [--out DIR]
"""

import argparse
from pathlib import Path
from statistics import mean

from .availability import DEFAULT_IN_PLAY, load_in_play
from .gamedata import DEFAULT_DATA_DIR, load_outfits
from .ladders import CoolingLadder, EnergyLadder, generators, passive_coolers
from .settings import SOLAR_ENERGY_CASE, SOLAR_HEAT_CASE, SOLAR_MULTIPLIER

# Legacy sheet constants, for comparison.
LEGACY_HEAT_BELOW, LEGACY_HEAT_ABOVE, LEGACY_THRESHOLD = 7 / 810, 24 / 3240, 1000

HEAT_BANDS = [(100, 500), (500, 1000), (1000, 2000), (2000, 5000), (5000, 10000), (10000, 20000), (20000, 40000)]
ENERGY_BANDS = [(25, 100), (100, 250), (250, 500), (500, 1000), (1000, 2000), (2000, 4000)]


def _combo(counter):
    return ", ".join(f"{n}× {name}" for name, n in sorted(counter.items(), key=lambda kv: -kv[1]))


def _band_average(cost, lo, hi, step):
    return mean(cost(x) / x for x in range(lo, hi, step))


def cooling_report(ladder):
    lines = ["# Passive cooling ladder", "",
             "Least outfit space that gives at least a given amount of passive cooling, using only whole,",
             "in-play outfits. Generated by `python -m sheetcalc`.", "",
             "## Candidate coolers", "",
             "| Cooler | Space | Cooling/s | Per space | Limit | On ladder? |", "|---|---|---|---|---|---|"]
    used = ladder.used()
    for c in sorted(ladder.coolers, key=lambda c: -c.cooling / c.space):
        lines.append(f"| {c.name} | {c.space} | {c.cooling:.0f} | {c.cooling / c.space:.1f} | "
                     f"{c.max_count or '—'} | {'yes' if c.name in used else 'obsolete'} |")
    lines += ["", "## Rate by ship heat band", "",
              "Average space per heat/s over the band, from the exact ladder. Use as the heat price",
              "(\"heat compensated outfit space\" multiplier) for a ship whose *total* heat is in that band.", "",
              "| Ship heat/s | Space per heat/s | Legacy magic number | Exact ÷ legacy |", "|---|---|---|---|"]
    for lo, hi in HEAT_BANDS:
        rate = _band_average(ladder.space_for, lo, hi, 5)
        legacy = LEGACY_HEAT_BELOW if hi <= LEGACY_THRESHOLD else LEGACY_HEAT_ABOVE
        lines.append(f"| {lo}–{hi} | {rate:.5f} | {legacy:.5f} | {rate / legacy:.2f} |")
    lines += ["", "## Ladder (up to 250 space)", "", "| Space | Cooling/s | Per space | Combination |", "|---|---|---|---|"]
    for s, cooling, combo in ladder.rungs():
        if s > 250:
            break
        lines.append(f"| {s} | {cooling:.0f} | {cooling / s:.1f} | {_combo(combo)} |")
    return "\n".join(lines) + "\n"


def energy_report(items, excluded, ladder, cooling):
    used = ladder.used()
    lines = ["# Energy generation ladder", "",
             "Least outfit space (generators **plus the passive cooling for their own heat**) that gives at",
             "least a given net energy per second, using only whole, in-play outfits.",
             f"Solar energy at the {SOLAR_ENERGY_CASE} case (×{SOLAR_MULTIPLIER[SOLAR_ENERGY_CASE]:.3f}), "
             f"solar heat at the {SOLAR_HEAT_CASE} case (×{SOLAR_MULTIPLIER[SOLAR_HEAT_CASE]:.3f}).",
             "Generated by `python -m sheetcalc`.", "",
             "## Price by energy band", "",
             "Average space per energy/s over the band. Use as the energy price for a ship whose *total*",
             "energy draw is in that band.", "",
             "| Ship energy/s | Space per energy/s | Energy/s per space |", "|---|---|---|"]
    top = ladder.rungs[-1][1]
    for lo, hi in ENERGY_BANDS:
        if hi > top:
            break
        rate = _band_average(ladder.space_for, lo, hi, 5)
        lines.append(f"| {lo}–{hi} | {rate:.4f} | {1 / rate:.2f} |")
    singles = [i for i in items if " + " not in i.name]
    lines += ["", "## Single generators, each with its own cooling", "",
              "| Generator | Space | + cooling | Energy/s | Heat/s | Energy/s per total space | Limit | On ladder? |",
              "|---|---|---|---|---|---|---|---|"]
    for i in sorted(singles, key=lambda i: -i.energy / (i.space + cooling.space_for(i.heat))):
        c = cooling.space_for(i.heat)
        lines.append(f"| {i.name} | {i.space} | {c} | {i.energy:.1f} | {i.heat:.0f} | "
                     f"{i.energy / (i.space + c):.2f} | {i.max_count or '—'} | {'yes' if i.name in used else 'obsolete'} |")
    composites = sorted({i.name.split(' + ')[0] for i in items if " + " in i.name})
    used_composites = sorted(n for n in used if " + " in n)
    lines += ["", f"Composites considered: {', '.join(c + ' + slot outfits' for c in composites)}.",
              f"Composites on the ladder: {', '.join(used_composites) or 'none'}."]
    if excluded:
        lines += ["", "Excluded: " + "; ".join(f"{n} ({why})" for n, why in excluded.items()) + "."]
    lines += ["", "## Ladder (selected rungs)", "",
              "| Total space | Energy/s | Per space | Generators | Cooling | Combination |", "|---|---|---|---|---|---|"]
    for total, energy, s, heat, combo in ladder.rungs:
        if total <= 60 or total % 10 == 0:
            lines.append(f"| {total} | {energy:.1f} | {energy / total:.2f} | {s} | {total - s} | {_combo(combo)} |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", default=DEFAULT_DATA_DIR, type=Path)
    parser.add_argument("--in-play", default=DEFAULT_IN_PLAY, type=Path)
    parser.add_argument("--out", default=Path(__file__).resolve().parents[1] / "reports", type=Path)
    args = parser.parse_args()

    outfits = load_outfits(args.data)
    availability = load_in_play(args.in_play)
    missing = sorted(n for n in availability if n not in outfits)
    if missing:
        raise SystemExit(f"In-play outfits not found in game data: {missing}")

    cooling = CoolingLadder(passive_coolers(outfits, availability))
    items, excluded = generators(outfits, availability)
    energy = EnergyLadder(items, cooling)

    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "cooling_ladder.md").write_text(cooling_report(cooling), encoding="utf-8")
    (args.out / "energy_ladder.md").write_text(energy_report(items, excluded, energy, cooling), encoding="utf-8")
    print(f"Wrote {args.out / 'cooling_ladder.md'} and {args.out / 'energy_ladder.md'}")


if __name__ == "__main__":
    main()
